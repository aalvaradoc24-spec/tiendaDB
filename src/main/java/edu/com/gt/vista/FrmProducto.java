    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
                                                                                 
    // Capturamos el texto escrito por el usuario en cada campo.
    String codigo = txtCodigo.getText().trim();
    String nombre = txtNombre.getText().trim();
    String categoria = txtCategoria.getText().trim();
    String precioTexto = txtPrecio.getText().trim();
    String stockTexto = txtStock.getText().trim();

    // Validamos que ningún campo esté vacío.
    if (codigo.isEmpty() || nombre.isEmpty() || categoria.isEmpty()
            || precioTexto.isEmpty() || stockTexto.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Debe llenar todos los campos.");
        return;
    }

    // Variables para guardar el precio y el stock convertidos.
    double precio;
    int stock;

    // Validamos que el precio sea numérico y mayor que cero.
    try {
        precio = Double.parseDouble(precioTexto);

        if (precio <= 0) {
            JOptionPane.showMessageDialog(this, "El precio debe ser mayor que cero.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El precio debe ser un número válido.");
        return;
    }

    // Validamos que el stock sea numérico y no negativo.
    try {
        stock = Integer.parseInt(stockTexto);

        if (stock < 0) {
            JOptionPane.showMessageDialog(this, "El stock no puede ser negativo.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El stock debe ser un número entero válido.");
        return;
    }

    // Consulta SQL para guardar el producto.
    String sql = "INSERT INTO Producto (codigo, nombre, categoria, precio, stock) "
               + "VALUES (?, ?, ?, ?, ?)";

    try {
        // Abrimos la conexión con SQL Server.
        Connection con = Conexion.getConexion();

        // Validamos que la conexión no venga vacía.
        if (con == null) {
            JOptionPane.showMessageDialog(this, "No se pudo conectar a la base de datos.");
            return;
        }

        // PreparedStatement evita errores y ayuda a prevenir inyección SQL.
        PreparedStatement ps = con.prepareStatement(sql);

        // Enviamos los valores a los signos ? del INSERT.
        ps.setString(1, codigo);
        ps.setString(2, nombre);
        ps.setString(3, categoria);
        ps.setDouble(4, precio);
        ps.setInt(5, stock);

        // Ejecutamos el INSERT.
        int filasGuardadas = ps.executeUpdate();

        // Verificamos si realmente se guardó.
        if (filasGuardadas > 0) {

            JOptionPane.showMessageDialog(this, "Producto guardado correctamente.");

            // ESTA ES LA LÍNEA QUE TE FALTABA.
            listarProductos();

            // Limpiamos los campos.
            txtCodigo.setText("");
            txtNombre.setText("");
            txtCategoria.setText("");
            txtPrecio.setText("");
            txtStock.setText("");

            // Regresamos el cursor al campo Código.
            txtCodigo.requestFocus();

        } else {
            JOptionPane.showMessageDialog(this, "No se pudo guardar el producto.");
        }

        // Cerramos recursos.
        ps.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al guardar:\n" + e.getMessage());
    }


    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
                                                                                    
    // Primero verificamos si el usuario seleccionó un producto.
    if (idSeleccionado == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla para modificar.");
        return;
    }

    // Capturamos los datos escritos en los campos.
    String codigo = txtCodigo.getText().trim();
    String nombre = txtNombre.getText().trim();
    String categoria = txtCategoria.getText().trim();
    String precioTexto = txtPrecio.getText().trim();
    String stockTexto = txtStock.getText().trim();

    // Validamos que ningún campo esté vacío.
    if (codigo.isEmpty() || nombre.isEmpty() || categoria.isEmpty()
            || precioTexto.isEmpty() || stockTexto.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Debe llenar todos los campos.");
        return;
    }

    // Variables para convertir precio y stock.
    double precio;
    int stock;

    // Validamos que el precio sea numérico y mayor que cero.
    try {
        precio = Double.parseDouble(precioTexto);

        if (precio <= 0) {
            JOptionPane.showMessageDialog(this, "El precio debe ser mayor que cero.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El precio debe ser un número válido.");
        return;
    }

    // Validamos que el stock sea numérico y no negativo.
    try {
        stock = Integer.parseInt(stockTexto);

        if (stock < 0) {
            JOptionPane.showMessageDialog(this, "El stock no puede ser negativo.");
            return;
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El stock debe ser un número entero válido.");
        return;
    }

    // Consulta SQL para modificar el producto seleccionado.
    String sql = "UPDATE Producto SET codigo=?, nombre=?, categoria=?, precio=?, stock=? WHERE id=?";

    try {
        // Abrimos la conexión.
        Connection con = Conexion.getConexion();

        // Validamos conexión.
        if (con == null) {
            JOptionPane.showMessageDialog(this, "No se pudo conectar a la base de datos.");
            return;
        }

        // Preparamos la consulta SQL.
        PreparedStatement ps = con.prepareStatement(sql);

        // Enviamos los nuevos datos.
        ps.setString(1, codigo);
        ps.setString(2, nombre);
        ps.setString(3, categoria);
        ps.setDouble(4, precio);
        ps.setInt(5, stock);

        // Enviamos el ID del producto que se va a modificar.
        ps.setInt(6, idSeleccionado);

        // Ejecutamos el UPDATE.
        int filasModificadas = ps.executeUpdate();

        // Verificamos si realmente se modificó.
        if (filasModificadas > 0) {

            JOptionPane.showMessageDialog(this, "Producto modificado correctamente.");

            // Esta línea actualiza el JTable.
            listarProductos();

            // Limpiamos los campos.
            txtCodigo.setText("");
            txtNombre.setText("");
            txtCategoria.setText("");
            txtPrecio.setText("");
            txtStock.setText("");

            // Reiniciamos el ID seleccionado.
            idSeleccionado = 0;

            // Quitamos la selección de la tabla.
            tblProducto.clearSelection();

            // Regresamos el cursor al campo Código.
            txtCodigo.requestFocus();

        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el producto para modificar.");
        }

        // Cerramos recursos.
        ps.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al modificar:\n" + e.getMessage());
    }

            
    }//GEN-LAST:event_btnModificarActionPerformed

    private void tblProductoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductoMouseClicked
        
                                              

    // Obtenemos la fila seleccionada.
    int fila = tblProducto.getSelectedRow();

    // Validamos que sí exista una fila seleccionada.
    if (fila >= 0) {

        /*
            IMPORTANTE:
            Esto asume que tu tabla tiene el ID en la columna 0.
            Luego vienen: Código, Nombre, Categoría, Precio y Stock.
        */
        idSeleccionado = Integer.parseInt(tblProducto.getValueAt(fila, 0).toString());

        txtCodigo.setText(tblProducto.getValueAt(fila, 1).toString());
        txtNombre.setText(tblProducto.getValueAt(fila, 2).toString());
        txtCategoria.setText(tblProducto.getValueAt(fila, 3).toString());
        txtPrecio.setText(tblProducto.getValueAt(fila, 4).toString());
        txtStock.setText(tblProducto.getValueAt(fila, 5).toString());
    }

        
    }//GEN-LAST:event_tblProductoMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
                                                   
                                                  

    // Validamos que el usuario haya seleccionado un producto
    if (idSeleccionado == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla para eliminar.");
        return;
    }

    // Pedimos confirmación antes de eliminar
    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de eliminar este producto?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    // Si el usuario presiona NO, cancelamos
    if (confirmacion != JOptionPane.YES_OPTION) {
        return;
    }

    // Consulta SQL para eliminar por ID
    String sql = "DELETE FROM Producto WHERE id = ?";

    try {
        // Abrimos la conexión con SQL Server
        Connection con = Conexion.getConexion();

        // Validamos que sí haya conexión
        if (con == null) {
            JOptionPane.showMessageDialog(this, "No se pudo conectar a la base de datos.");
            return;
        }

        // Preparamos la consulta
        PreparedStatement ps = con.prepareStatement(sql);

        // Enviamos el ID del producto que queremos eliminar
        ps.setInt(1, idSeleccionado);

        // Ejecutamos el DELETE
        int filasEliminadas = ps.executeUpdate();

        // Verificamos si realmente se eliminó
        if (filasEliminadas > 0) {

            JOptionPane.showMessageDialog(this, "Producto eliminado correctamente.");

            // Esta línea actualiza el JTable
            listarProductos();

            // Limpiamos los campos
            txtCodigo.setText("");
            txtNombre.setText("");
            txtCategoria.setText("");
            txtPrecio.setText("");
            txtStock.setText("");

            // Reiniciamos el ID seleccionado
            idSeleccionado = 0;

        } else {
            JOptionPane.showMessageDialog(this, "No se encontró el producto para eliminar.");
        }

        // Cerramos recursos
        ps.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al eliminar:\n" + e.getMessage());
    }

        
    }//GEN-LAST:event_btnEliminarActionPerformed

