    private void listarProductos() {
        // Modelo de la tabla, aquí definimos las columnas que aparecerán
    javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel();

    // Agregamos las columnas de la tabla
    modelo.addColumn("ID");
    modelo.addColumn("Código");
    modelo.addColumn("Nombre");
    modelo.addColumn("Categoría");
    modelo.addColumn("Precio");
    modelo.addColumn("Stock");

    // Consulta SQL para traer todos los productos
    String sql = "SELECT id, codigo, nombre, categoria, precio, stock FROM Producto";

    try {
        // Abrimos la conexión con SQL Server
        Connection con = Conexion.getConexion();

        // Validamos que la conexión no sea nula
        if (con == null) {
            JOptionPane.showMessageDialog(this, "No se pudo conectar a la base de datos.");
            return;
        }

        // Preparamos la consulta SELECT
        PreparedStatement ps = con.prepareStatement(sql);

        // Ejecutamos la consulta
        ResultSet rs = ps.executeQuery();

        // Recorremos los registros encontrados
        while (rs.next()) {

            // Creamos una fila para la tabla
            Object[] fila = new Object[6];

            // Llenamos la fila con datos de SQL Server
            fila[0] = rs.getInt("id");
            fila[1] = rs.getString("codigo");
            fila[2] = rs.getString("nombre");
            fila[3] = rs.getString("categoria");
            fila[4] = rs.getDouble("precio");
            fila[5] = rs.getInt("stock");

            // Agregamos la fila al modelo
            modelo.addRow(fila);
        }

        // Mostramos el modelo en la tabla
        tblProducto.setModel(modelo);

        // Cerramos recursos
        rs.close();
        ps.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al listar productos:\n" + e.getMessage());
    }
    }
   
